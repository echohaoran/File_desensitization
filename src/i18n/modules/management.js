// Rust commands may reject with an object or a serialized object.
// Translate known codes and use a localized fallback for unknown native diagnostics.
export function localizeManagementError(error, translate, fallback = 'unknownError') {
  if (error?.managementLocalized) return error.message
  let detail = error
  if (typeof detail === 'string') {
    try { detail = JSON.parse(detail) } catch { /* Plain native error message. */ }
  }
  if (errorKeys.has(detail?.code)) return translate('management.error_' + detail.code)
  const message = typeof detail === 'string' ? detail : detail?.message
  const legacyKey = legacyErrors[message]
  if (legacyKey) return translate('management.' + legacyKey)
  const knownKey = Object.keys(messages.zh.management).find(key => key.startsWith('error_') && messages.zh.management[key] === message)
  if (knownKey) return translate('management.' + knownKey)
  const localized = translate('management.' + fallback)
  return typeof detail?.code === 'string' && /^[A-Z0-9_]+$/.test(detail.code)
    ? translate('management.errorWithCode', { message: localized, code: detail.code })
    : localized
}

